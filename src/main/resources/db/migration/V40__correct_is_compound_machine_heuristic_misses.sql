-- 機能見直し-1-#1: V39の分類（マシン/カール/レイズ等のキーワードヒューリスティック）を
-- 実データ目視レビューした結果、以下は「マシン」等の語を含むために単関節(is_compound=0)へ
-- 誤分類されていたが、実際には複数関節を動員する複合種目(is_compound=1)であるため補正する。
--
-- 判断基準（設計書と同じ「複合(多関節)/単関節」の定義）:
--   ・プレス系（胸/肩の押す動作）は肩関節+肘関節を動員 → 複合種目
--     例: スミスマシンベンチプレス、スミスマシンインクラインベンチプレス、
--         チェストプレスマシン、ショルダープレスマシン、ショルダーブレスマシン
--         （「ショルダーブレスマシン」は登録データ上の表記だが同種のプレス系種目のため同様に補正）
--   ・ロウ系（背中の引く動作）は肩関節+肘関節を動員 → 複合種目
--     例: シーテッドロウマシン、ローローマシン
--   ・プルアップ（懸垂）系は肩関節+肘関節を動員 → 複合種目
--     例: アシストプルアップマシン
--   ・スクワット系は股関節+膝関節+足関節を動員 → 複合種目
--     例: スミスマシンスクワット
--
-- （フライ系・レイズ系・カール系・エクステンション系・カーフレイズ等の単関節種目はV39の分類のまま
--  変更しない。ヒップスラストマシンは股関節単独の動きのため単関節のまま据え置く）
UPDATE training_item_master
SET is_compound = 1
WHERE item_name IN (
  'アシストプルアップマシン',
  'シーテッドロウマシン',
  'ローローマシン',
  'スミスマシンインクラインベンチプレス',
  'スミスマシンベンチプレス',
  'チェストプレスマシン',
  'スミスマシンスクワット',
  'ショルダーブレスマシン',
  'ショルダープレスマシン'
)
AND is_compound = 0;
